public enum TransitionResult
{
    /// <summary>First time this payment is seen.</summary>
    Created,
    /// <summary>Status moved forward (e.g. pending → completed).</summary>
    Advanced,
    /// <summary>Same status again, or an older status arriving late — nothing to do.</summary>
    NoChange,
}

/// <summary>Payment lifecycle rules. A status may only move forward:
/// pending → completed | failed;  completed → reversed.  failed and reversed are final.</summary>
public static class PaymentStateMachine
{
    public static TransitionResult Apply(string? current, string incoming)
    {
        if (!ProviderPaymentStatuses.All.Contains(incoming)) throw new ArgumentException($"Unknown status '{incoming}'.");
        if (current is null) return TransitionResult.Created;
        if (current == incoming) return TransitionResult.NoChange;
        return (current, incoming) switch
        {
            (ProviderPaymentStatuses.Pending, ProviderPaymentStatuses.Completed) => TransitionResult.Advanced,
            (ProviderPaymentStatuses.Pending, ProviderPaymentStatuses.Failed) => TransitionResult.Advanced,
            (ProviderPaymentStatuses.Completed, ProviderPaymentStatuses.Reversed) => TransitionResult.Advanced,
            _ => TransitionResult.NoChange, // e.g. "pending" arriving after "completed"
        };
    }

    /// <summary>Only completed payments count as income. Pending is never confirmed income.</summary>
    public static bool CountsAsIncome(string status) => status == ProviderPaymentStatuses.Completed;
}
